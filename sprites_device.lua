-- Returns false when there is no sprite for that device, so callers can fall back.
function sprites_device.draw(name, ox, oy, active, focused_knob)
  local sp = sprites_device.SPRITES[name]
  if not sp then return false end
  for slot, pts in pairs(sp) do
    local lv
    if     slot == 12 then lv = active and FULL or MED
    elseif slot >= 13 then lv = ((slot - 12) == focused_knob) and FULL or MED
    else                   lv = MED end
    screen.level(lv)
    for _, p in ipairs(pts) do screen.rect(ox + p[1], oy + p[2], 1, 1) end
    screen.fill()
  end
  return true
end

return sprites_device
