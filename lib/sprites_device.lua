sprites_device.INV = { BG = 15, BG_DIM = 6, KNOB = 9, KNOB_DIM = 3, LAMP_OFF = 9 }

function sprites_device.draw(name, ox, oy, active, focused_knob, inverted, focused)
  local sp = sprites_device.SPRITES[name]
  if not sp then return false end
  local INV = sprites_device.INV
  for slot, pts in pairs(sp) do
    local lv
    if inverted then
      if     slot == 12 then lv = active and 0 or INV.LAMP_OFF
      elseif slot >= 13 then lv = ((slot - 12) == focused_knob) and 0 or (focused and INV.KNOB or INV.KNOB_DIM)
      else                   lv = 0 end
    elseif slot == 12 then lv = active and FULL or MED
    elseif slot >= 13 then lv = ((slot - 12) == focused_knob) and FULL or MED
    else                   lv = slot <= 10 and slot or MED end
    screen.level(lv)
    sprite.rects(pts, ox, oy)
    screen.fill()
  end
  return true
end

return sprites_device
