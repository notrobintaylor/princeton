local PEDAL_BY_NAME = {
  push       = PEDAL_PUSH,
  distort    = PEDAL_DISTORT,
  warp       = PEDAL_WARP,
  ["repeat"] = PEDAL_REPEAT,
}

function sprites.draw_pedal(ox, oy, name, display, bypassed, focused_knob)
  local sp = PEDAL_BY_NAME[name:lower()]
  if sp then
    local oy_sprite = oy - 1
    local fs_lv     = bypassed and MED or FULL
    local focus_slot  = (focused_knob == 1 and 13)
                   or (focused_knob == 2 and 14)
                   or (focused_knob == 3 and 15)
                   or (focused_knob == 4 and 16)
                   or nil
    for slot, pts in pairs(sp) do
      local sl
      if     slot == 12       then sl = fs_lv
      elseif slot == focus_slot then sl = FULL
      else                         sl = MED end
      screen.level(sl)
      for _, pt in ipairs(pts) do screen.rect(ox + pt[1], oy_sprite + pt[2], 1, 1) end
      screen.fill()
    end
  end
  screen.font_size(8); screen.font_face(0)
  screen.level(bypassed and MED or FULL)
  screen.move(ox + 16, oy + 56); screen.text_center(display)
end

